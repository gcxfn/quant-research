def load_reasons():
    reasons = {}
    for fp in sorted(glob.glob(os.path.join(RAW, "chunk_*.csv"))):
        with open(fp, encoding="utf-8", newline="") as fh:
            for r in csv.DictReader(fh):
                key = (r["ts_code"].strip(), (r.get("end_date") or "").strip(),
                       (r.get("ann_date") or "").strip(),
                       (r.get("update_flag") or "").strip())
                reasons[key] = r.get("change_reason") or ""
    return reasons


def main():
    import polars as pl
    idx = pl.read_parquet(os.path.join(
        ROOT, "data", "features", "fcst-reason-struct-full-20260918", "row_index.parquet"))
    meta = {r["ordinal"]: r for r in
            idx.filter(pl.col("batch_id") == 26).iter_rows(named=True)}
    reasons = load_reasons()

    problems = []
    seen = set()
    for ordinal, p, s, d, q, c in R:
        if ordinal in seen:
            problems.append(f"{ordinal}: duplicate")
        seen.add(ordinal)
        if p not in VOCAB:
            problems.append(f"{ordinal}: primary {p} not in vocab")
        if s is not None and (s not in VOCAB or s == p):
            problems.append(f"{ordinal}: secondary {s} invalid")
        if d not in (-1, 0, 1):
            problems.append(f"{ordinal}: dir {d}")
        if c not in ("high", "low"):
            problems.append(f"{ordinal}: conf {c}")
        if not 0 < len(q) <= 40:
            problems.append(f"{ordinal}: quote len {len(q)}")
        m = meta.get(ordinal)
        if m is None:
            problems.append(f"{ordinal}: not in row_index batch 26")
            continue
        key = (m["ts_code"], m["end_date"], m["ann_date"], m["update_flag"])
        orig = reasons.get(key)
        if orig is None:
            problems.append(f"{ordinal}: raw row missing")
        elif q not in orig:
            problems.append(f"{ordinal}: quote NOT verbatim: {q!r}")
    if sorted(seen) != list(range(15000, 15600)):
        missing = set(range(15000, 15600)) - seen
        problems.append(f"missing ordinals: {sorted(missing)[:20]}")

    if problems:
        print("SELF-CHECK FAILURES:", len(problems))
        for x in problems:
            print("  ", x)
        raise SystemExit(1)

    for part in range(1, 7):
        lo = 15000 + (part - 1) * 100
        rows = [r for r in R if lo <= r[0] < lo + 100]
        path = os.path.join(WORK, f"batch_026_judge_part{part}.jsonl")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            for ordinal, p, s, d, q, c in rows:
                f.write(json.dumps({
                    "ordinal": ordinal, "primary_code": p,
                    "secondary_code": s, "supports_direction": d,
                    "key_quote": q, "confidence": c,
                }, ensure_ascii=False, separators=(",", ":")) + "\n")
        print(f"part{part}: {len(rows)} rows -> {path}")

    from collections import Counter
    pc = Counter(r[1] for r in R)
