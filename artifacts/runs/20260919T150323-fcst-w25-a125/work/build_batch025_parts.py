def main():
    cues = {}
    with io.open(WORK / "batch_025_cues.txt", "r", encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\r\n")
            if not line:
                continue
            ordinal, reason = line.split("|", 1)
            cues[int(ordinal)] = reason

    errors = []
    for ordinal, primary, secondary, sd, quote, conf in J:
        if primary not in VOCAB:
            errors.append(f"{ordinal}: primary_code 非法 {primary}")
        if secondary is not None and secondary not in VOCAB:
            errors.append(f"{ordinal}: secondary_code 非法 {secondary}")
        if secondary == primary:
            errors.append(f"{ordinal}: secondary 与 primary 相同")
        if sd not in (-1, 0, 1):
            errors.append(f"{ordinal}: supports_direction 非法 {sd}")
        if conf not in ("high", "low"):
            errors.append(f"{ordinal}: confidence 非法 {conf}")
        if len(quote) > 40:
            errors.append(f"{ordinal}: key_quote 超长 {len(quote)}")
        reason = cues.get(ordinal)
        if reason is None:
            errors.append(f"{ordinal}: cues 中不存在")
        elif quote not in reason:
            errors.append(f"{ordinal}: key_quote 不是逐字子串: {quote}")

    if errors:
        print("SELF-CHECK FAILED:")
        for e in errors:
            print(" ", e)
        sys.exit(1)

    ords = [j[0] for j in J]
    assert ords == list(range(14400, 15000)), "ordinal 不连续"

    for part in range(1, 7):
        lo = 14400 + (part - 1) * 100
        hi = lo + 99
        rows = [j for j in J if lo <= j[0] <= hi]
        assert len(rows) == 100
        out = WORK / f"batch_025_judge_part{part}.jsonl"
        with io.open(out, "w", encoding="utf-8", newline="\n") as f:
            for ordinal, primary, secondary, sd, quote, conf in rows:
                obj = {"ordinal": ordinal, "primary_code": primary,
                       "secondary_code": secondary, "supports_direction": sd,
                       "key_quote": quote, "confidence": conf}
                f.write(json.dumps(obj, ensure_ascii=False) + "\n")
        print(f"wrote {out} ({len(rows)} rows)")

    # stats
    from collections import Counter
    pc = Counter(j[1] for j in J)
    sec_null = sum(1 for j in J if j[2] is None)
    cf = Counter(j[5] for j in J)
    sd = Counter(j[3] for j in J)
    print("rows:", len(J))
    print("primary_code:", dict(sorted(pc.items(), key=lambda x: -x[1])))
    print("secondary_null_rate: %.3f" % (sec_null / len(J)))
    print("confidence:", dict(cf))
    print("supports_direction:", dict(sorted(sd.items())))

if __name__ == "__main__":
    main()
